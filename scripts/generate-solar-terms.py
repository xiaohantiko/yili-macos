#!/usr/bin/env python3
"""Regenerate the app's solar-term instants using Skyfield 1.55 and JPL DE440s.

Install Skyfield in a Python environment, then download de440s.bsp from
https://naif.jpl.nasa.gov/pub/naif/generic_kernels/spk/planets/de440s.bsp
and run `python scripts/generate-solar-terms.py /path/to/de440s.bsp`.
The generated Swift table is the only ephemeris data included in the app.
"""

import argparse
import hashlib
from pathlib import Path

import numpy as np
from skyfield import __version__ as skyfield_version
from skyfield.almanac import find_discrete
from skyfield.api import load, load_file
from skyfield.framelib import ecliptic_frame

FIRST_YEAR = 1900
LAST_YEAR = 2100
KERNEL_SHA256 = "c1c7feeab882263fc493a9d5a5b2ddd71b54826cdf65d8d17a76126b260a49f2"


def generate(kernel):
    if skyfield_version != "1.55":
        raise ValueError("Install skyfield==1.55 for the pinned Earth-rotation model.")
    if hashlib.sha256(kernel.read_bytes()).hexdigest() != KERNEL_SHA256:
        raise ValueError("The SHA-256 does not match the JPL DE440s kernel.")

    timescale = load.timescale(builtin=True)
    ephemeris = load_file(str(kernel))
    earth, sun = ephemeris["earth"], ephemeris["sun"]

    def longitude_sector(time):
        apparent = earth.at(time).observe(sun).apparent()
        _, longitude, _ = apparent.frame_latlon(ecliptic_frame)
        return np.floor(longitude.degrees / 15).astype(int)

    # Adjacent crossings are at least about two weeks apart.
    longitude_sector.step_days = 10
    expected_sectors = [(19 + index) % 24 for index in range(24)]
    start = timescale.ut1(FIRST_YEAR, 1, 1)
    end = timescale.ut1(LAST_YEAR + 1, 1, 1)
    instants, sectors = find_discrete(start, end, longitude_sector)
    if sectors.tolist() != expected_sectors * (LAST_YEAR - FIRST_YEAR + 1):
        raise ValueError("A solar term is missing or out of order.")

    lines = [
        "// Generated by scripts/generate-solar-terms.py. Do not edit by hand.",
        "// JPL DE440s: apparent geocentric longitude in the true ecliptic of date.",
        "// Each row is seconds since Jan 1 00:00 UT1, rounded to a whole second.",
        "// Terms are in chronological order from 小寒 (285°) to 冬至 (270°).",
        "// UT1 approximates the civil UTC clock, with future timing subject to ΔT uncertainty.",
        "enum SolarTermTable {",
        f"    static let firstYear = {FIRST_YEAR}",
        "    static let secondsByYear: [[Int32]] = [",
    ]
    for row, year in enumerate(range(FIRST_YEAR, LAST_YEAR + 1)):
        begin = timescale.ut1(year, 1, 1).ut1
        elapsed_seconds = (instants[row * 24:(row + 1) * 24].ut1 - begin) * 86_400
        values = ", ".join(str(int(value)) for value in np.rint(elapsed_seconds))
        lines.append(f"        [{values}], // {year}")
    lines.extend(["    ]", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("kernel", type=Path, help="Path to the official de440s.bsp")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    output = root / "Sources" / "YiLiCore" / "SolarTermTable.swift"
    output.write_text(generate(args.kernel), encoding="utf-8")


if __name__ == "__main__":
    main()
